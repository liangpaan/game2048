def P(text, style=body):
    return Paragraph(text, style)


def table(data, widths, font_size=8.7, header=True, row_bgs=True):
    converted = []
    for ri, row in enumerate(data):
        converted.append([P(str(cell), small if font_size < 10 else body) for cell in row])
    t = Table(converted, colWidths=widths, repeatRows=1 if header else 0, hAlign='LEFT')
    cmds = [
        ('GRID', (0, 0), (-1, -1), .35, colors.HexColor('#cbd5e1')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 2.4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2.4),
    ]
    if header:
        cmds += [('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#dbeafe')),
                 ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#0f172a'))]
    if row_bgs:
        for row in range(1 if header else 0, len(data)):
            if row % 2 == 0:
                cmds.append(('BACKGROUND', (0, row), (-1, row), colors.HexColor('#f8fafc')))
    t.setStyle(TableStyle(cmds))
    return t


